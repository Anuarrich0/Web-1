const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({ window: {}, console });
for (const file of ['main.js', 'training.js', 'services.js', 'locations.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, 'assets/js', file), 'utf8'), context, { filename: file });
}
const EF = context.window.EF;
const rules = EF.rules;
const dateString = date => date.getFullYear() + '-' + String(date.getMonth() + 1).padStart(2, '0') + '-' + String(date.getDate()).padStart(2, '0');
const today = new Date();
const future = days => new Date(today.getFullYear(), today.getMonth(), today.getDate() + days);
for (const value of ['', 'bad', '2026-02-31', '2026-13-01', dateString(future(-1))]) assert.ok(rules.notPastDate(value), value);
assert.equal(rules.notPastDate(dateString(today)), '');
assert.equal(rules.withinDays(dateString(future(30)), 30), '');
assert.ok(rules.withinDays(dateString(future(31)), 30));
assert.ok(rules.withinDays('invalid', 30));
for (const value of ['', 'NaN', 'Infinity', '-Infinity', '13', '91']) assert.ok(rules.numberRange(value, 14, 90));
assert.ok(rules.numberRange('25.5', 14, 90, true));
assert.equal(rules.numberRange('25', 14, 90, true), '');
assert.equal(rules.numberRange('70.5', 35, 250), '');
assert.ok(rules.fullName('Анна'));
assert.equal(rules.fullName('Әлия Нұрланқызы'), '');
assert.ok(rules.phone('+1 700 123 45 67'));
assert.ok(rules.phone('+7 700 123 45 678'));
assert.equal(rules.phone('+7 700 123 45 67'), '');
assert.equal(vm.runInContext("formatPhone('+17001234567')", context), '+17001234567');
assert.equal(vm.runInContext("formatPhone('+7 700 123 45 678999999')", context), '+7 700 123 45 67');
assert.equal(vm.runInContext("limitNumberInput('123456789', '99')", context), '12');
assert.equal(vm.runInContext("limitNumberInput('17599999', '230')", context), '175');
assert.equal(vm.runInContext("limitNumberInput('70.56789', '250', '0.1')", context), '70.5');
assert.equal(vm.runInContext("limitNumberInput('1e5', '99')", context), '');
assert.ok(rules.maxLength('x'.repeat(2001), 2000));
assert.equal(rules.maxLength('x'.repeat(2000), 2000), '');
assert.ok(rules.email('a'.repeat(250) + '@example.com'));
const plan = EF.buildFitnessPlan({ gender: 'male', age: 25, height: 175, weight: 70, activity: 'moderate', goal: 'maintain' });
assert.equal(plan.bmr, 1674);
assert.equal(plan.tdee, 2595);
assert.equal(plan.targetCalories, 2595);
assert.equal(plan.workoutFrequency, 2);
assert.equal(EF.buildFitnessPlan({ gender: 'male', age: 25, height: 175, weight: 70, activity: 'moderate', goal: 'lose' }).targetCalories, 2195);
for (const trainer of EF.TRAINERS) assert.ok(trainer.slots.every(slot => slot.day !== 'sunday'));
for (const branch of EF.BRANCHES) assert.equal(branch.phone.replace(/\D/g, ''), branch.phoneHref.replace(/\D/g, ''));
console.log('PASS: shared browser rules, invalid dates, booking range, phone overflow, fractional input and fitness calculations.');
